import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from collections import Counter
import warnings
warnings.filterwarnings('ignore')

class RenalHMM:
    """
    Modelo Oculto de Markov para Enfermedad Renal Crónica (ERC)
    Estados ocultos: progresión de la enfermedad
    Observaciones: niveles de creatinina y síntomas clínicos
    """
    def __init__(self):
        # Estados ocultos (progresión de ERC)
        self.states = ['Leve', 'Moderado', 'Severo', 'Diálisis', 'Trasplante']
        self.n_states = len(self.states)

        # Observaciones (niveles de creatinina en mg/dL)
        self.observations = ['Creatinina Normal', 'Creatinina Elevada', 'Creatinina Muy Alta', 'Diálisis Requerida']
        self.n_observations = len(self.observations)

        # Mapeos
        self.state_to_idx = {state: idx for idx, state in enumerate(self.states)}
        self.obs_to_idx = {obs: idx for idx, obs in enumerate(self.observations)}
        self.idx_to_state = {idx: state for state, idx in self.state_to_idx.items()}
        self.idx_to_obs = {idx: obs for obs, idx in self.obs_to_idx.items()}

        # Matriz de transición (basada en datos clínicos de Colombia 2025)
        #            Leve   Mod    Sev    Dial   Transpl
        self.transition_matrix = np.array([
            [0.70, 0.25, 0.04, 0.01, 0.00],  # Leve
            [0.10, 0.60, 0.25, 0.05, 0.00],  # Moderado
            [0.00, 0.15, 0.55, 0.28, 0.02],  # Severo
            [0.00, 0.00, 0.00, 0.85, 0.15],  # Diálisis
            [0.05, 0.00, 0.00, 0.10, 0.85]   # Trasplante
        ])

        # Matriz de emisión (probabilidad de observar cada nivel de creatinina)
        # Basado en valores clínicos: creatinina normal <1.2, elevada 1.2-3.0, muy alta >3.0 mg/dL
        #            CreatNorm  CreatElev  CreatMuyAlt  DialReq
        self.emission_matrix = np.array([
            [0.85, 0.12, 0.03, 0.00],  # Leve
            [0.25, 0.55, 0.18, 0.02],  # Moderado
            [0.05, 0.25, 0.60, 0.10],  # Severo
            [0.00, 0.05, 0.15, 0.80],  # Diálisis
            [0.20, 0.50, 0.25, 0.05]   # Trasplante
        ])

        # Distribución inicial (paciente recién diagnosticado en Colombia)
        self.initial_prob = np.array([0.80, 0.15, 0.04, 0.01, 0.00])

        # Costos en COP 2025 (mensuales asociados a cada estado)
        self.costos_mensuales = {
            'Leve': 300_000,
            'Moderado': 800_000,
            'Severo': 2_000_000,
            'Diálisis': 2_500_000,
            'Trasplante': 3_500_000
        }

        # Costos de transición únicos (eventos críticos)
        self.costos_transicion = {
            'a_dialisis': 5_000_000,
            'a_trasplante': 95_000_000,
            'fallo_trasplante': 12_000_000
        }

        # Almacenamiento de datos
        self.true_states = []
        self.observations_seq = []
        self.inferred_states = []
        self.confidence_scores = []
        self.costos_acumulados = []

    def generate_sequence(self, n_months=24):
        """
        Genera una secuencia de estados ocultos y observaciones (creatinina)
        """
        # Generar primer estado según distribución inicial
        current_state = np.random.choice(self.n_states, p=self.initial_prob)
        self.true_states = [current_state]

        # Registrar costo inicial
        estado_nombre = self.idx_to_state[current_state]
        self.costos_acumulados = [self.costos_mensuales[estado_nombre]]

        # Primera observación (nivel de creatinina)
        current_obs = np.random.choice(self.n_observations,
                                       p=self.emission_matrix[current_state])
        self.observations_seq = [current_obs]

        # Generar meses restantes
        for _ in range(n_months - 1):
            estado_anterior = current_state
            estado_anterior_nombre = self.idx_to_state[estado_anterior]

            # Transición a nuevo estado
            current_state = np.random.choice(self.n_states,
                                            p=self.transition_matrix[current_state])
            self.true_states.append(current_state)

            # Calcular costo del mes (incluyendo costo de transición si aplica)
            estado_nuevo_nombre = self.idx_to_state[current_state]
            costo_mes = self.costos_mensuales[estado_nuevo_nombre]

            # Agregar costo de transición si hubo cambio significativo
            if estado_anterior_nombre != estado_nuevo_nombre:
                if estado_nuevo_nombre == 'Diálisis':
                    costo_mes += self.costos_transicion['a_dialisis']
                elif estado_nuevo_nombre == 'Trasplante':
                    costo_mes += self.costos_transicion['a_trasplante']
                elif estado_nuevo_nombre == 'Diálisis' and estado_anterior_nombre == 'Trasplante':
                    costo_mes += self.costos_transicion['fallo_trasplante']

            self.costos_acumulados.append(self.costos_acumulados[-1] + costo_mes)

            # Emitir observación (nivel de creatinina)
            current_obs = np.random.choice(self.n_observations,
                                          p=self.emission_matrix[current_state])
            self.observations_seq.append(current_obs)

        return self.true_states, self.observations_seq, self.costos_acumulados

    def viterbi_algorithm(self):
        """
        Algoritmo de Viterbi para encontrar la secuencia más probable de estados
        """
        n_months = len(self.observations_seq)

        # Inicialización
        V = np.zeros((self.n_states, n_months))  # Probabilidades
        path = np.zeros((self.n_states, n_months), dtype=int)  # Backpointer

        # Primer mes
        V[:, 0] = self.initial_prob * self.emission_matrix[:, self.observations_seq[0]]

        # Iterar sobre los meses
        for t in range(1, n_months):
            for s in range(self.n_states):
                probabilities = V[:, t-1] * self.transition_matrix[:, s] * \
                               self.emission_matrix[s, self.observations_seq[t]]
                V[s, t] = np.max(probabilities)
                path[s, t] = np.argmax(probabilities)

        # Recuperar la secuencia más probable
        best_path = np.zeros(n_months, dtype=int)
        best_path[-1] = np.argmax(V[:, -1])

        for t in range(n_months-2, -1, -1):
            best_path[t] = path[best_path[t+1], t+1]

        # Calcular confianza del diagnóstico
        self.confidence_scores = np.max(V, axis=0)

        return best_path

    def calculate_clinical_metrics(self):
        """
        Calcula métricas clínicas relevantes para ERC
        """
        # Tiempo en cada estado
        state_counts = Counter(self.true_states)
        months_per_state = {self.idx_to_state[s]: count for s, count in state_counts.items()}

        # Tiempo hasta diálisis (meses hasta llegar a estado Diálisis)
        time_to_dialysis = None
        for idx, state in enumerate(self.true_states):
            if state == self.state_to_idx['Diálisis']:
                time_to_dialysis = idx
                break

        # Tiempo hasta trasplante (si aplica)
        time_to_transplant = None
        for idx, state in enumerate(self.true_states):
            if state == self.state_to_idx['Trasplante']:
                time_to_transplant = idx
                break

        # Progresión rápida (transición Leve → Severo o Moderado → Diálisis en <12 meses)
        rapid_progression = False
        for i in range(len(self.true_states) - 12):
            if (self.true_states[i] == self.state_to_idx['Leve'] and
                self.true_states[i+12] >= self.state_to_idx['Severo']):
                rapid_progression = True
                break
            if (self.true_states[i] == self.state_to_idx['Moderado'] and
                self.true_states[i+12] == self.state_to_idx['Diálisis']):
                rapid_progression = True
                break

        # Probabilidad de requerir diálisis
        requiere_dialisis = self.state_to_idx['Diálisis'] in self.true_states

        # Probabilidad de trasplante
        recibe_trasplante = self.state_to_idx['Trasplante'] in self.true_states

        # Costo total y promedio mensual
        costo_total = self.costos_acumulados[-1] if self.costos_acumulados else 0
        costo_promedio_mensual = costo_total / len(self.true_states) if self.true_states else 0

        return {
            'months_per_state': months_per_state,
            'time_to_dialysis_months': time_to_dialysis,
            'time_to_transplant_months': time_to_transplant,
            'rapid_progression': rapid_progression,
            'requires_dialysis': requiere_dialisis,
            'receives_transplant': recibe_trasplante,
            'total_cost_cop': costo_total,
            'avg_monthly_cost_cop': costo_promedio_mensual
        }

    def infer_and_evaluate(self):
        """
        Inferencia con Viterbi y evaluación de precisión
        """
        self.inferred_states = self.viterbi_algorithm()

        correct_predictions = sum(1 for i in range(len(self.true_states))
                                 if self.true_states[i] == self.inferred_states[i])
        accuracy = correct_predictions / len(self.true_states)

        return accuracy

